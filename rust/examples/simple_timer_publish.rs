use aorta_sdk::log_prelude::*;

/// Simple Timer Publish Example
///
/// Demonstrates using publish() with timer callbacks (synchronous fire-and-forget).
/// No need for .await - publish() works in any context (async/sync/timer).
///
/// Run with: bazel run //rust/examples:simple_timer_publish
use aorta_sdk::{HeaderInjector, HeaderValues, Node, SchemaMeta};
use flatbuffers::{FlatBufferBuilder, WIPOffset};
use std::sync::atomic::{AtomicU64, Ordering};
use std::sync::Arc;
use std::time::Duration;

// Minimal message schema implementations (no external .fbs files needed)
mod simple_msg {
    use flatbuffers::{FlatBufferBuilder, WIPOffset};

    // Simple counter message table
    pub fn create_counter_msg<'a>(
        builder: &mut FlatBufferBuilder<'a>,
        header: WIPOffset<crate::AortaHeader<'a>>,
        counter: u64,
        value: f64,
    ) -> WIPOffset<CounterMsg<'a>> {
        let mut msg_builder = CounterMsgBuilder::new(builder);
        msg_builder.add_aorta_header(header);
        msg_builder.add_counter(counter);
        msg_builder.add_value(value);
        msg_builder.finish()
    }

    // Generated by FlatBuffers (simplified for example)
    pub struct CounterMsg<'a> {
        _tab: flatbuffers::Table<'a>,
    }

    impl<'a> flatbuffers::Follow<'a> for CounterMsg<'a> {
        type Inner = CounterMsg<'a>;
        #[inline]
        unsafe fn follow(buf: &'a [u8], loc: usize) -> Self::Inner {
            Self {
                _tab: flatbuffers::Table::new(buf, loc),
            }
        }
    }

    pub struct CounterMsgBuilder<'a: 'b, 'b> {
        fbb_: &'b mut FlatBufferBuilder<'a>,
        start_: flatbuffers::WIPOffset<flatbuffers::TableUnfinishedWIPOffset>,
    }

    impl<'a: 'b, 'b> CounterMsgBuilder<'a, 'b> {
        pub fn new(fbb: &'b mut FlatBufferBuilder<'a>) -> CounterMsgBuilder<'a, 'b> {
            let start = fbb.start_table();
            CounterMsgBuilder {
                fbb_: fbb,
                start_: start,
            }
        }

        pub fn add_aorta_header(&mut self, aorta_header: WIPOffset<crate::AortaHeader<'a>>) {
            self.fbb_.push_slot_always::<WIPOffset<_>>(0, aorta_header);
        }

        pub fn add_counter(&mut self, counter: u64) {
            self.fbb_.push_slot::<u64>(1, counter, 0);
        }

        pub fn add_value(&mut self, value: f64) {
            self.fbb_.push_slot::<f64>(2, value, 0.0);
        }

        pub fn finish(self) -> WIPOffset<CounterMsg<'a>> {
            let o = self.fbb_.end_table(self.start_);
            WIPOffset::new(o.value())
        }
    }
}

// Minimal AortaHeader implementation
pub struct AortaHeader<'a> {
    _tab: flatbuffers::Table<'a>,
}

impl<'a> flatbuffers::Follow<'a> for AortaHeader<'a> {
    type Inner = AortaHeader<'a>;
    #[inline]
    unsafe fn follow(buf: &'a [u8], loc: usize) -> Self::Inner {
        Self {
            _tab: flatbuffers::Table::new(buf, loc),
        }
    }
}

struct AortaHeaderBuilder<'a: 'b, 'b> {
    fbb_: &'b mut FlatBufferBuilder<'a>,
    start_: flatbuffers::WIPOffset<flatbuffers::TableUnfinishedWIPOffset>,
}

impl<'a: 'b, 'b> AortaHeaderBuilder<'a, 'b> {
    pub fn new(fbb: &'b mut FlatBufferBuilder<'a>) -> AortaHeaderBuilder<'a, 'b> {
        let start = fbb.start_table();
        AortaHeaderBuilder {
            fbb_: fbb,
            start_: start,
        }
    }

    pub fn add_publish_stamp_ns(&mut self, publish_stamp_ns: u64) {
        self.fbb_.push_slot::<u64>(0, publish_stamp_ns, 0);
    }

    pub fn add_publisher_node(&mut self, publisher_node: WIPOffset<&'a str>) {
        self.fbb_
            .push_slot_always::<WIPOffset<_>>(1, publisher_node);
    }

    pub fn add_sequence(&mut self, sequence: u64) {
        self.fbb_.push_slot::<u64>(2, sequence, 0);
    }

    pub fn finish(self) -> WIPOffset<AortaHeader<'a>> {
        let o = self.fbb_.end_table(self.start_);
        WIPOffset::new(o.value())
    }
}

// Schema metadata for our simple counter message
struct SimpleCounterSchema;

impl SchemaMeta for SimpleCounterSchema {
    fn schema_bfbs() -> &'static [u8] {
        // Empty schema for demo purposes
        &[]
    }
}

impl HeaderInjector for SimpleCounterSchema {
    type Header<'a> = AortaHeader<'a>;

    fn build_header<'b>(
        builder: &mut FlatBufferBuilder<'b>,
        values: &HeaderValues<'_>,
    ) -> WIPOffset<Self::Header<'b>> {
        let node = builder.create_string(values.publisher_node);
        let mut header_builder = AortaHeaderBuilder::new(builder);
        header_builder.add_publish_stamp_ns(values.publish_stamp_ns);
        header_builder.add_publisher_node(node);
        header_builder.add_sequence(values.sequence);
        header_builder.finish()
    }
}

#[tokio::main]
async fn main() -> Result<(), Box<dyn std::error::Error>> {
    aorta_info!("=== Aorta Simple Timer Publish Example ===\n");

    let node = Node::new("simple_timer_pub", "default").await?;
    aorta_info!("Created node: {}\n", node.name());

    // Create publisher
    let publisher = node
        .create_publisher::<SimpleCounterSchema>("/simple/counter")
        .await?;

    aorta_info!("Created publisher on topic: {}\n", publisher.topic());

    // Shared counter
    let counter = Arc::new(AtomicU64::new(0));
    let counter_clone = Arc::clone(&counter);

    // Create timer with 100ms interval
    aorta_info!("Creating timer (100ms interval)...\n");

    let timer = node
        .create_timer(Duration::from_millis(100), move || {
            let count = counter_clone.fetch_add(1, Ordering::Relaxed);
            let value = (count as f64 * 0.1).sin() * 100.0;

            if count % 10 == 0 {
                aorta_info!("  [TIMER] Published message #{}: value={:.2}", count, value);
            }

            // Use publish() - synchronous fire-and-forget, works in any context!
            let _ = publisher.publish(move |builder, header| {
                let msg = simple_msg::create_counter_msg(builder, header, count, value);
                builder.finish(msg, None);
            });
        })
        .await?;

    aorta_info!("=== Publishing messages for 10 seconds... ===\n");
    aorta_info!("(Using synchronous publish() in timer callback - no .await needed!)\n");

    // Run for 10 seconds
    tokio::time::sleep(Duration::from_secs(10)).await;

    let final_count = counter.load(Ordering::Relaxed);
    aorta_info!("\n=== Statistics ===");
    aorta_info!("Total messages published: {}", final_count);
    aorta_info!("Expected ~100 messages (10s * 10Hz)");

    // Cleanup
    timer.pause();
    node.close().await?;

    aorta_info!("\n=== Example Complete ===");
    Ok(())
}
