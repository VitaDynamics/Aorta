#!/usr/bin/env python3
"""Render the vendored `FlatBuffersConfig*.cmake` from `flatbuffers/base.h`.

The bundle ships the FlatBuffers runtime, and every generated
header in the bundle `static_assert`s on an EXACT FlatBuffers version, which no
Ubuntu 22.04 package provides (the distro ships 1.12.1). The bundle therefore
vendors the same headers Aorta itself compiled against, plus a package config
so `find_package(FlatBuffers CONFIG)` resolves inside the archive.

The version is read out of the vendored `base.h` rather than repeated here, so
the config can never claim a version the shipped headers do not implement.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

_VERSION_FIELDS = ("MAJOR", "MINOR", "REVISION")

_CONFIG_TEMPLATE = """# Generated by tools/release/gen_flatbuffers_cmake.py -- do not edit.
#
# Header-only FlatBuffers {version} runtime vendored into the Aorta SDK bundle.
# The bundle's generated headers static_assert on exactly this version.

get_filename_component(_FLATBUFFERS_PREFIX "${{CMAKE_CURRENT_LIST_DIR}}/../../.." ABSOLUTE)

set(FlatBuffers_VERSION "{version}")
set(FLATBUFFERS_INCLUDE_DIRS "${{_FLATBUFFERS_PREFIX}}/include")

if(NOT EXISTS "${{FLATBUFFERS_INCLUDE_DIRS}}/flatbuffers/flatbuffers.h")
  set(FlatBuffers_FOUND FALSE)
  set(FlatBuffers_NOT_FOUND_MESSAGE
    "vendored FlatBuffers headers are missing from ${{FLATBUFFERS_INCLUDE_DIRS}}")
  unset(_FLATBUFFERS_PREFIX)
  return()
endif()

if(NOT TARGET flatbuffers::flatbuffers)
  add_library(flatbuffers::flatbuffers INTERFACE IMPORTED)
  set_target_properties(flatbuffers::flatbuffers PROPERTIES
    INTERFACE_INCLUDE_DIRECTORIES "${{FLATBUFFERS_INCLUDE_DIRS}}")
endif()

set(FlatBuffers_FOUND TRUE)
unset(_FLATBUFFERS_PREFIX)
"""

_VERSION_TEMPLATE = """# Generated by tools/release/gen_flatbuffers_cmake.py -- do not edit.
set(PACKAGE_VERSION "{version}")

if(PACKAGE_VERSION VERSION_LESS PACKAGE_FIND_VERSION)
  set(PACKAGE_VERSION_COMPATIBLE FALSE)
else()
  set(PACKAGE_VERSION_COMPATIBLE TRUE)
  if(PACKAGE_FIND_VERSION VERSION_EQUAL PACKAGE_VERSION)
    set(PACKAGE_VERSION_EXACT TRUE)
  endif()
endif()
"""


def read_version(base_header: str) -> str:
    """FlatBuffers `MAJOR.MINOR.REVISION` as declared by `flatbuffers/base.h`."""
    values = []
    for field in _VERSION_FIELDS:
        match = re.search(
            rf"^#define\s+FLATBUFFERS_VERSION_{field}\s+(\d+)\s*$",
            base_header,
            re.MULTILINE,
        )
        if match is None:
            raise ValueError(f"flatbuffers/base.h declares no FLATBUFFERS_VERSION_{field}")
        values.append(match.group(1))
    return ".".join(values)


def render(base_header: str) -> tuple[str, str]:
    version = read_version(base_header)
    return (
        _CONFIG_TEMPLATE.format(version=version),
        _VERSION_TEMPLATE.format(version=version),
    )


def main() -> int:
    parser = argparse.ArgumentParser()
    parser.add_argument("--base-header", type=Path, required=True)
    parser.add_argument("--config-output", type=Path, required=True)
    parser.add_argument("--version-output", type=Path, required=True)
    args = parser.parse_args()
    config, version = render(args.base_header.read_text(encoding="utf-8"))
    args.config_output.write_text(config, encoding="utf-8")
    args.version_output.write_text(version, encoding="utf-8")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
